public class AveragePCM {
    public static void main(String[] args) {
        // Marks in each subject
        int maths = 94;
        int physics = 95;
        int chemistry = 96;
        
        // Calculate average
        double average = (maths + physics + chemistry) / 3.0;
        
        // Print the result
        System.out.println("Sam’s average mark in PCM is " + average);
    }
}